-- Esquema del prototipo. Es SQL estándar para que corra igual en PostgreSQL y en H2 (pruebas).

CREATE TABLE doctor (
    id          VARCHAR(20)  PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    label       VARCHAR(120) NOT NULL,
    specialty   VARCHAR(80)  NOT NULL,
    sort_order  INT          NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE patient (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id VARCHAR(20)  NOT NULL,
    full_name   VARCHAR(120) NOT NULL,
    phone       VARCHAR(30)  NOT NULL,
    doctor_id   VARCHAR(20)  NOT NULL REFERENCES doctor (id),
    last_visit  DATE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_patient_document UNIQUE (document_id)
);

CREATE TABLE treatment (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(80) NOT NULL,
    base_price           BIGINT,
    default_duration_min INT         NOT NULL DEFAULT 60,
    CONSTRAINT uq_treatment_name UNIQUE (name)
);

CREATE TABLE appointment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   BIGINT       REFERENCES patient (id) ON DELETE SET NULL,
    patient_name VARCHAR(120) NOT NULL,
    treatment    VARCHAR(120) NOT NULL DEFAULT '',
    doctor_id    VARCHAR(20)  NOT NULL REFERENCES doctor (id),
    scheduled_on DATE         NOT NULL,
    start_time   TIME         NOT NULL,
    duration_min INT          NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_appointment_status CHECK (status IN ('confirmed', 'pending', 'urgent', 'cancelled')),
    CONSTRAINT ck_appointment_duration CHECK (duration_min > 0)
);
CREATE INDEX ix_appointment_doctor_date ON appointment (doctor_id, scheduled_on);
CREATE INDEX ix_appointment_date ON appointment (scheduled_on);
CREATE INDEX ix_appointment_patient ON appointment (patient_id);

CREATE TABLE pending_reschedule (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   BIGINT       REFERENCES patient (id) ON DELETE CASCADE,
    name         VARCHAR(120) NOT NULL,
    treatment    VARCHAR(120) NOT NULL DEFAULT '',
    phone        VARCHAR(30)  NOT NULL,
    requested_on DATE         NOT NULL
);

CREATE TABLE treatment_plan (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT       NOT NULL REFERENCES patient (id),
    concept     VARCHAR(120) NOT NULL,
    total_cost  BIGINT       NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_plan_cost CHECK (total_cost >= 0)
);
CREATE INDEX ix_plan_patient ON treatment_plan (patient_id);

CREATE TABLE payment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id    BIGINT       NOT NULL REFERENCES treatment_plan (id) ON DELETE CASCADE,
    paid_on    DATE         NOT NULL,
    concept    VARCHAR(160) NOT NULL,
    amount     BIGINT       NOT NULL,
    method     VARCHAR(20)  NOT NULL,
    signature  VARCHAR(80)  NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_method CHECK (method IN ('Efectivo', 'Transferencia', 'Datáfono'))
);
CREATE INDEX ix_payment_plan ON payment (plan_id);
CREATE INDEX ix_payment_paid_on ON payment (paid_on);

CREATE TABLE reminder (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT      NOT NULL REFERENCES appointment (id) ON DELETE CASCADE,
    status         VARCHAR(20) NOT NULL DEFAULT 'pending',
    CONSTRAINT uq_reminder_appointment UNIQUE (appointment_id),
    CONSTRAINT ck_reminder_status CHECK (status IN ('pending', 'confirmed'))
);

-- Saldo por paciente: costo de sus tratamientos menos lo abonado. No se guarda en una columna para no duplicarlo.
CREATE VIEW patient_balance AS
SELECT p.id AS patient_id,
       COALESCE(plans.total_cost, 0)                              AS total_cost,
       COALESCE(paid.total_paid, 0)                               AS total_paid,
       COALESCE(plans.total_cost, 0) - COALESCE(paid.total_paid, 0) AS balance
FROM patient p
LEFT JOIN (SELECT patient_id, CAST(SUM(total_cost) AS BIGINT) AS total_cost
           FROM treatment_plan GROUP BY patient_id) plans ON plans.patient_id = p.id
LEFT JOIN (SELECT tp.patient_id, CAST(SUM(pay.amount) AS BIGINT) AS total_paid
           FROM payment pay JOIN treatment_plan tp ON tp.id = pay.plan_id
           GROUP BY tp.patient_id) paid ON paid.patient_id = p.id;
